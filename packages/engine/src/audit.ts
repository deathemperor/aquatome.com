import { readdir, readFile } from 'node:fs/promises'
import { join } from 'node:path'

type Photo = { url: string; thumb?: string }
export type AuditRow = { page: string; name: string; photos: number; missingThumbs: number }

/** Every species, plant and guide by picture count: none, photos without a card thumb, or one photo (nothing inside the text). */
export async function auditPictures(contentRoot: string): Promise<{ rows: AuditRow[]; markdown: string }> {
  const rows: AuditRow[] = []
  for (const kind of ['species', 'plants', 'guides']) {
    for (const id of (await readdir(join(contentRoot, kind)).catch(() => [] as string[])).sort()) {
      const raw = await readFile(join(contentRoot, kind, id, 'entity.json'), 'utf8').catch(() => null)
      if (!raw) continue
      const photos: Photo[] = JSON.parse(raw).photos ?? []
      const vi = JSON.parse(await readFile(join(contentRoot, kind, id, 'vi.json'), 'utf8').catch(() => '{}')) as { name?: string }
      rows.push({ page: `${kind}/${id}`, name: vi.name ?? id, photos: photos.length, missingThumbs: photos.filter(p => !p.thumb).length })
    }
  }
  const list = (title: string, xs: AuditRow[]) => `## ${title} (${xs.length})\n\n${xs.map(r => `- ${r.page} — ${r.name}`).join('\n') || '- none'}\n`
  const markdown = `# Content pictures audit

Generated by \`pnpm engine audit\` every engine cycle. Pages are listed, not hidden. Guides without a photo of their own
borrow one from a species or plant they mention on the site.

${list('No photo', rows.filter(r => !r.photos))}
${list('Photos without a card thumbnail', rows.filter(r => r.missingThumbs))}
${list('Only one photo (no pictures inside the text)', rows.filter(r => r.photos === 1))}`
  return { rows, markdown }
}
