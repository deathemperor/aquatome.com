import { readFileSync, writeFileSync } from 'node:fs'
import { expect, test } from 'vitest'
import { frameOf, SUBJECT_CUT, SUBJECT_SLACK, type SubjectFractions, type SubjectFrame } from '../src/index'

// Shared with the iOS app, whose tests run its own frame rule on the same cases. Every `frame`, and the file's `cut` and
// `slack`, are generated here from the site's rule (image-geometry.ts frameOf): UPDATE_VECTORS=1 rewrites them.
const FILE = new URL('../../../protocols/photo-crop-vectors.json', import.meta.url)
type Case = { note: string; w: number; h: number; box: SubjectFractions | null; ratio: number; frame?: SubjectFrame }
const kept: { cases: Case[] } = JSON.parse(readFileSync(FILE, 'utf8'))

const COMMENT = 'How a frame shows a fish\'s photo so it keeps the fish (packages/schema/src/image-geometry.ts subjectFrame; the Design Lead\'s look for each frame: docs of the frames board). For a frame of `ratio` (width over height) and a photo `w` by `h` with the fish\'s `box` (fractions of the photo from its top-left corner, as `box` and `imgBox` carry it): the frame covers the photo with a window of its shape, which cuts one side of the photo only. The fish\'s loss is the share of the box\'s length along that side that falls outside the window. (1) The centred window, if it loses `cut` or less (plus `slack`, so the last bit of a window\'s edge can\'t turn exactly `cut` into more); (2) else the window centred on the box, kept inside the photo, if it loses `cut` or less; (3) else the photo whole. No box (null): the centred window, never whole. `frame`: {"fit": "cover", "x", "y"} places the window as CSS object-position does (its offset over the room it has to move, 0.5 where it has none), or {"fit": "whole"}. Each box is as the app is sent it (four places, rounded outward from the photo\'s pixels: boxFractions), and the site decides on those same fractions (subjectFrame is frameOf on them), so both decide alike; positions agree to `tolerance`. Generated by packages/schema/test/photo-crop-vectors.test.ts from the site\'s rule: edit a case\'s inputs here (note, w, h, box, ratio), then run UPDATE_VECTORS=1 on that test file, which writes every frame and `cut`; the test fails while the file differs from what the rule gives. The app\'s tests are to hold its own rule and cut to this file.'

/** One case a line, as the other vector files are laid out. */
const line = (o: unknown): string => Array.isArray(o) ? `[${o.map(line).join(', ')}]`
  : o !== null && typeof o === 'object' ? `{${Object.entries(o).map(([k, x]) => `${JSON.stringify(k)}: ${line(x)}`).join(', ')}}`
  : JSON.stringify(o)

test('protocols/photo-crop-vectors.json is what the site\'s rule gives for its cases', () => {
  const cases = kept.cases.map(({ note, w, h, box, ratio }) => {
    if (box) {
      // As boxFractions sends it: four places, inside the photo.
      for (const v of [box.x, box.y, box.w, box.h]) expect(Math.abs(v * 1e4 - Math.round(v * 1e4)), `${note}: four places`).toBeLessThan(1e-6)
      expect(box.x + box.w <= 1 + 1e-9 && box.y + box.h <= 1 + 1e-9 && box.w > 0 && box.h > 0, `${note}: inside the photo`).toBe(true)
    }
    return { note, w, h, box, ratio, frame: frameOf(w / h, box ?? undefined, ratio) }
  })
  const next = [
    '{',
    `  "$comment": ${JSON.stringify(COMMENT)},`,
    `  "cut": ${SUBJECT_CUT},`,
    `  "slack": ${SUBJECT_SLACK},`,
    '  "tolerance": 1e-9,',
    '  "cases": [',
    ...cases.map((c, i) => `    ${line(c)}${i < cases.length - 1 ? ',' : ''}`),
    '  ]',
    '}',
    '',
  ].join('\n')
  if (process.env.UPDATE_VECTORS === '1') writeFileSync(FILE, next)
  expect(readFileSync(FILE, 'utf8'), 'run UPDATE_VECTORS=1 pnpm exec vitest run test/photo-crop-vectors.test.ts (packages/schema)').toBe(next)
  // The cases the v2 Lab asked for are all there, each deciding as its note says.
  const by = (note: string) => cases.find(c => c.note.includes(note))!.frame
  expect(by('no box').fit).toBe('cover')
  expect(by('exactly 5%,')).toEqual({ fit: 'cover', x: 0.5, y: 0.5 })
  expect(by('5.1%')).toMatchObject({ fit: 'cover', x: 0.5 })
  expect(by('the whole photo, in another shape')).toEqual({ fit: 'whole' })
})
